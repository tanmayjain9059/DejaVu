"""Private upload storage with local-filesystem and S3-compatible backends.

Use a private bucket (for example Cloudflare R2) and serve objects only through
authenticated application routes. Object keys are generated by the application;
client-supplied filenames are never used as keys.
"""
from __future__ import annotations

import os
import re
from functools import lru_cache
from pathlib import Path

from app.core import config

_KEY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


def _object_settings() -> tuple[str, str, str, str, str]:
    return (
        os.getenv("OBJECT_STORAGE_BUCKET", "").strip(),
        os.getenv("OBJECT_STORAGE_ENDPOINT_URL", "").strip(),
        os.getenv("OBJECT_STORAGE_ACCESS_KEY_ID", "").strip(),
        os.getenv("OBJECT_STORAGE_SECRET_ACCESS_KEY", "").strip(),
        os.getenv("OBJECT_STORAGE_REGION", "auto").strip() or "auto",
    )


def object_storage_enabled() -> bool:
    bucket, endpoint, access_key, secret_key, _ = _object_settings()
    configured = (bucket, endpoint, access_key, secret_key)
    if any(configured) and not all(configured):
        raise RuntimeError(
            "Configure OBJECT_STORAGE_BUCKET, OBJECT_STORAGE_ENDPOINT_URL, "
            "OBJECT_STORAGE_ACCESS_KEY_ID and OBJECT_STORAGE_SECRET_ACCESS_KEY together."
        )
    return all(configured)


def _safe_key(key: str) -> str:
    if not isinstance(key, str) or not _KEY_PATTERN.fullmatch(key) or key in {".", ".."}:
        raise ValueError("Invalid private upload key.")
    return key


@lru_cache(maxsize=1)
def _s3_client():
    bucket, endpoint, access_key, secret_key, region = _object_settings()
    if not all((bucket, endpoint, access_key, secret_key)):
        raise RuntimeError("Object storage is not fully configured.")
    try:
        import boto3
    except ImportError as exc:
        raise RuntimeError("Install the boto3 dependency to use object storage.") from exc
    return boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=access_key,
        aws_secret_access_key=secret_key,
        region_name=region,
    )


def store_upload(key: str, content: bytes) -> None:
    key = _safe_key(key)
    if object_storage_enabled():
        bucket = _object_settings()[0]
        _s3_client().put_object(
            Bucket=bucket, Key=key, Body=content, ContentType="image/jpeg",
            CacheControl="private, no-store",
        )
        return
    config.UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    target = (config.UPLOAD_DIR / key).resolve()
    if target.parent != config.UPLOAD_DIR.resolve():
        raise ValueError("Upload path is outside the configured directory.")
    target.write_bytes(content)


def read_upload(key: str) -> bytes:
    key = _safe_key(key)
    if object_storage_enabled():
        from botocore.exceptions import ClientError
        bucket = _object_settings()[0]
        try:
            response = _s3_client().get_object(Bucket=bucket, Key=key)
            return response["Body"].read()
        except ClientError as exc:
            code = str(exc.response.get("Error", {}).get("Code", ""))
            if code in {"NoSuchKey", "NoSuchBucket", "404", "NotFound"}:
                raise FileNotFoundError(key) from exc
            raise
    target = (config.UPLOAD_DIR / key).resolve()
    if target.parent != config.UPLOAD_DIR.resolve() or not target.is_file():
        raise FileNotFoundError(key)
    return target.read_bytes()


def delete_upload(key: str) -> None:
    key = _safe_key(key)
    if object_storage_enabled():
        bucket = _object_settings()[0]
        _s3_client().delete_object(Bucket=bucket, Key=key)
        return
    target = (config.UPLOAD_DIR / key).resolve()
    if target.parent != config.UPLOAD_DIR.resolve():
        raise ValueError("Upload path is outside the configured directory.")
    target.unlink(missing_ok=True)
